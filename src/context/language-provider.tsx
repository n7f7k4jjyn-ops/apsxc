function readInitialLanguage(): Language {
  if (typeof window === 'undefined') return 'pt-BR'
  try {
    return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'en' ? 'en' : 'pt-BR'
  } catch {
    return 'pt-BR'
  }
}

export function translateText(text: string, language: Language): string {
  const normalized = text.replace(/\s+/g, ' ').trim()
  return language === 'en' ? english[normalized] ?? text : text
}

export function getCurrentLanguage(): Language {
  return readInitialLanguage()
}

type LanguageContextValue = {
  language: Language
  setLanguage: (language: Language) => void
  translate: (text: string) => string
}

const LanguageContext = createContext<LanguageContextValue>({
  language: 'pt-BR',
  setLanguage: () => undefined,
  translate: (text) => text,
})

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(readInitialLanguage)
  const chooseLanguage = useCallback((nextLanguage: Language) => {
    setLanguage(nextLanguage)
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage)
    } catch {
      // The selected language still applies for this session if storage is unavailable.
    }
  }, [])
  const value = useMemo<LanguageContextValue>(
    () => ({ language, setLanguage: chooseLanguage, translate: (text) => translateText(text, language) }),
    [chooseLanguage, language]
  )

  useEffect(() => {
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language)
    } catch {
      // The selected language still applies for this session if storage is unavailable.
    }
    document.documentElement.lang = language === 'en' ? 'en' : 'pt-BR'
  }, [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  return useContext(LanguageContext)
}

export function LocalizedText({
  text,
  leadingSpace = false,
  trailingSpace = false,
}: {
  text: string
  leadingSpace?: boolean
  trailingSpace?: boolean
}) {
  const { translate } = useLanguage()
  return <>{leadingSpace ? ' ' : ''}{translate(text)}{trailingSpace ? ' ' : ''}</>
}
